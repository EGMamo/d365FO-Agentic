import type { AppConfig } from '../config/index.js';
import type { LlmTool } from '../llm/types.js';

/**
 * The model never sees D365_USERNAME / D365_PASSWORD. It asks for them through
 * this local tool. A trusted browser operation checks the live document's
 * origin and the actual Microsoft authentication input before filling it.
 * Model-supplied snapshots, references and descriptions grant no authority.
 */
export const CREDENTIAL_TOOL_NAME = 'd365_enter_credential';

export const CREDENTIAL_TOOL: LlmTool = {
  name: CREDENTIAL_TOOL_NAME,
  description:
    'Fill the configured D365 test-account username or password into the current Microsoft sign-in form. ' +
    'The app independently checks the live page origin and authentication control; the secret is never shown to you. ' +
    'Set `submit` to submit that verified sign-in form after filling it. Other pages and controls are refused.',
  inputSchema: {
    type: 'object',
    required: ['field'],
    properties: {
      field: { type: 'string', enum: ['username', 'password'] },
      submit: { type: 'boolean', description: 'Submit the verified authentication form after filling', default: false },
    },
  },
};

/** Exact HTTPS origins that may receive the saved Microsoft-account credentials. Never inferred from page text. */
export const CREDENTIAL_ORIGINS = ['https://login.microsoftonline.com', 'https://login.live.com'] as const;

/**
 * This code is generated by the app, never by the model, and sent only through an internal browser_run_code call.
 * Validation and filling execute synchronously in one live document, preventing a snapshot/fill navigation race.
 * The target is a known Microsoft input, not a model-chosen locator. An unsupported login page fails closed.
 */
export function credentialEntryCode(field: 'username' | 'password', value: string, submit: boolean): string {
  const input = JSON.stringify({ field, value, submit, origins: CREDENTIAL_ORIGINS });
  return `async (page) => page.evaluate(({ field, value, submit, origins }) => {
    const refuse = () => { throw new Error('Credential entry refused: the live page is not a supported Microsoft authentication form.'); };
    const url = new URL(location.href);
    if (window.top !== window || url.protocol !== 'https:' || url.username || url.password || !origins.includes(url.origin)) refuse();
    const id = field === 'password' ? 'i0118' : 'i0116';
    const name = field === 'password' ? 'passwd' : 'loginfmt';
    const matches = document.querySelectorAll('input#' + id);
    if (matches.length !== 1) refuse();
    const control = matches[0];
    const types = field === 'password' ? ['password'] : ['email', 'text'];
    const form = control.form;
    const style = getComputedStyle(control);
    if (!(control instanceof HTMLInputElement) || control.name !== name || !types.includes(control.type) ||
        control.disabled || control.readOnly || !control.isConnected || !control.getClientRects().length ||
        style.visibility !== 'visible' || style.display === 'none' || style.opacity === '0' || !form ||
        form.method.toLowerCase() !== 'post' || new URL(form.action, location.href).origin !== url.origin) refuse();
    const setter = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set;
    setter.call(control, value);
    control.dispatchEvent(new Event('input', { bubbles: true }));
    control.dispatchEvent(new Event('change', { bubbles: true }));
    if (submit) {
      if (location.origin !== url.origin || !control.isConnected || control.form !== form ||
          new URL(form.action, location.href).origin !== url.origin) refuse();
      form.requestSubmit();
    }
    return { ok: true, entered: field };
  }, ${input})`;
}

export function credentialFor(cfg: AppConfig, field: unknown): string | undefined {
  if (field === 'username') return cfg.D365_USERNAME || undefined;
  if (field === 'password') return cfg.D365_PASSWORD || undefined;
  return undefined;
}

const SECRET_KEYS = [
  'D365_PASSWORD',
  'D365_USERNAME',
  'ANTHROPIC_API_KEY',
  'ANTHROPIC_AUTH_TOKEN',
  'OPENAI_API_KEY',
  'OPENAI_COMPATIBLE_API_KEY',
  'AZURE_OPENAI_API_KEY',
  'GITHUB_TOKEN',
  'GITHUB_COPILOT_TOKEN',
  'AZDO_PAT',
  'D365_CLIENT_SECRET',
] as const;

// Token shapes that can show up in page text or errors even when they are not configured values.
const TOKEN_PATTERNS = [
  /\beyJ[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}\.[A-Za-z0-9_-]{8,}/g, // JWT
  /\bBearer\s+[A-Za-z0-9._~+/-]{20,}=*/gi,
  /\bgh[pousr]_[A-Za-z0-9]{30,}/g,
  /\bsk-[A-Za-z0-9_-]{20,}/g,
];

/** Replaces any configured secret, and anything shaped like an access token, in `text` with `***`. */
export function redactSecrets(cfg: Partial<Record<(typeof SECRET_KEYS)[number], string | undefined>>, text: string): string {
  let out = text;
  for (const key of SECRET_KEYS) {
    const secret = cfg[key];
    if (secret) out = out.split(secret).join('***');
  }
  for (const pattern of TOKEN_PATTERNS) out = out.replace(pattern, '***');
  return out;
}

/**
 * Builds the `browser_type` arguments for the installed Playwright MCP. Newer
 * releases take the snapshot reference as `target`; older ones as `ref`. The
 * server's input schema is strict, so only the key it declares may be sent.
 */
export function browserTypeArgs(
  schema: Record<string, unknown> | undefined,
  a: { ref: string; element?: string; text: string; submit?: boolean },
): Record<string, unknown> {
  const props = (schema?.properties ?? {}) as Record<string, unknown>;
  const refKey = 'target' in props || !('ref' in props) ? 'target' : 'ref';
  const args: Record<string, unknown> = { [refKey]: a.ref, text: a.text, submit: Boolean(a.submit) };
  if (a.element && (!schema || 'element' in props)) args.element = a.element;
  return args;
}

/** Flattens an MCP error result into short text, with credentials redacted by the caller. */
export function mcpErrorText(content: unknown): string {
  if (Array.isArray(content)) {
    const t = content
      .map((c) => (c && typeof c === 'object' && 'text' in c ? String((c as { text: unknown }).text) : ''))
      .filter(Boolean)
      .join('\n');
    if (t) return t;
  }
  return typeof content === 'string' ? content : JSON.stringify(content);
}
